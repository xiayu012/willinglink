/**
 * **受约束回复的确定性 grounding 闸——纯代码，读不了模型心思，只挡可证的越界。**
 *
 * `unsupported` 保留轮与**统一产品功能问答**都是**无工具、无第三方出站**的小回复路径：
 * 代码只提供"这件事办不了 / 现在能做什么"的事实，**没有提供任何处理方案**，所以模型
 * 也不许自行补一个。corpus-035 实跑暴露过两类越界（同一轮一条）：
 *
 * 1. **把球踢回住户**：「你可能得直接跟他说一下」「你可以自己找房东」「你们自己沟通」——
 *    等于让住户去做 AI 做不了的事；本路径既没有这个能力、也没有安排任何后续。
 * 2. **承诺 AI 替住户去做**：「我这就去跟阿川说」「有结果我回你」——本路径没有工具，
 *    这是假话。
 *
 * 这两条对**所有**受约束回复都一样，所以收在一个共享的纯函数里，**不是按主题分叉的
 * 程序**：换一个未开放事项、换一句问法，规则一字不改。命中任何一条都返回可诊断短语，
 * 调用方据此换成**只含代码事实**的兜底——绝不放一句把球踢回去、画大饼或假承诺的正文。
 *
 * 只属于某一条路径的格式约束（正文长度、内部术语黑名单）留在各自模块里，不进这里。
 *
 * 本文件**不 import 任何东西**：`unsupported.ts` 与 `feature-qa.ts` 都能直接用，不会成环。
 */

/**
 * 第一人称假承诺：本路径没有工具，任何「我去联系 / 我去跟他说 / 有了结果回你」都是没做
 * 的事。只抓**主动承诺动作**——`转达` 这类纯说明用词不在动作词里，免得把「这件事不是
 * 我能替你转达的」这种真话也误伤。
 */
const FALSE_PROMISE =
  /已经(?:跟|和|向|把|联系|找|说|问)|我(?:会|将|要|待会儿|马上|这就|回头|先|再去|自己|这边|去)[^。！？]{0,6}(?:去)?(?:跟|和|向|找|联系|转告|告诉|说一声|说一下|问一下|问一问|问问|催|沟通|协调|处理|了解|跟进|答复|回你)|(?:帮|替)你[^。！？]{0,6}(?:去)?(?:跟|和|向|找|联系|转告|告诉|说|问|催|沟通|协调|处理|了解|跟进|回)|有(?:了)?结果[^。！？]{0,4}(?:我)?(?:再)?(?:回|告诉|跟|和|说|答复)|(?:回头|以后|下次|过会|一会|一会儿|待会儿)[^。！？]{0,6}(?:再)?(?:跟|和|告诉|回|答复|处理|安排|沟通)|我(?:去)?(?:跟|和)(?:他|她|他们|对方)/;

/**
 * 第三人称对象：任何「让住户去找对方」的宾语。**刻意不含「我」**——让住户找 AI（找
 * 当前说话人自己）不算把事推回给他。
 */
const THIRD_PARTY =
  "(?:他|她|他们|她们|对方|那(?:位|个|人)|房东|物业|管理员|中介|别人|其他人|第三方|阿[\\u4e00-\\u9fff])";

/**
 * 句内停顿/断句：**跨越逗号、分号、换行就不算同一句**。少了这一条，「这件事我现在没法
 * 替你发给对方，还没有跟他说」会被误判成「你……跟他说」的建议——那是中性兜底原句本身。
 */
const NO_BREAK = "[^。！？；;，,、：:！!?\\n]";

/** 建议语气/情态词：只有「你 + 情态 + 联系动作」才算把事推给住户。 */
const MODAL =
  "(?:可以|可|得|要|最好|不如|应该|应当|需要|必须|自己|亲自|直接|试着|考虑|去|先|就|还是|干脆)";

/** 让住户自己去联系某个第三人（情态词是必要的，避免把「没法替你联系他」误伤成建议）。 */
const OFFLOAD_CONTACT = new RegExp(
  `(?:你|您|你们|您们)${NO_BREAK}{0,6}${MODAL}${NO_BREAK}{0,6}(?:去)?(?:跟|和|找|联系|问|向)${NO_BREAK}{0,4}${THIRD_PARTY}`
);

/** 让住户自己去说 / 沟通 / 处理（「你们自己沟通一下」）。 */
const OFFLOAD_SELF = new RegExp(
  `(?:你|您|你们|您们)${NO_BREAK}{0,4}自己${NO_BREAK}{0,6}(?:说|讲|聊|沟通|协调|商量|协商|处理|解决|联系|找|问|催)`
);

/** 无主语的推脱建议（「建议找房东协调」「最好跟他商量」）。 */
const OFFLOAD_SUGGEST = new RegExp(
  `(?:建议|不如|最好|可以考虑)${NO_BREAK}{0,6}(?:找|联系|跟|和)${NO_BREAK}{0,4}${THIRD_PARTY}`
);

/** 「换个方式 / 别的渠道」——本路径没有渠道可换。 */
const ALT_CHANNEL =
  /(?:换个?(?:方式|渠道|办法|途径|平台)|(?:别的|其他|其它)(?:方式|渠道|途径|平台))/;

/** 「以后 / 下次 / 回头 …… 再说 / 再处理」——本路径没有安排任何后续。 */
const DEFER_TO_LATER = new RegExp(
  `(?:以后|下次|回头|将来|过(?:阵子|段时间)|等${NO_BREAK}{0,8}(?:再|后))${NO_BREAK}{0,6}(?:再|才)?(?:说|讲|聊|谈|处理|解决|办|弄|商量|协调|联系|找|问)`
);

/**
 * 找出正文里**可证的越界**，返回可诊断短语（空数组 = 通过）。调用方据此换成只含代码
 * 事实的兜底。
 */
export function findGroundingViolations(reply: string): string[] {
  const text = (reply ?? "").trim();
  if (!text) return ["空正文"];
  const out: string[] = [];
  if (FALSE_PROMISE.test(text)) {
    out.push("承诺自己去联系 / 协调 / 跟进（本路径没有这种能力）");
  }
  if (
    OFFLOAD_CONTACT.test(text) ||
    OFFLOAD_SELF.test(text) ||
    OFFLOAD_SUGGEST.test(text)
  ) {
    out.push("建议住户自己去找对方 / 找别人");
  }
  if (ALT_CHANNEL.test(text)) {
    out.push("建议住户换别的渠道 / 方式");
  }
  if (DEFER_TO_LATER.test(text)) {
    out.push("把处理推到以后（本路径没有安排后续）");
  }
  return out;
}
