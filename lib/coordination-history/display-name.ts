/**
 * 「协调历史」页上**一套房显示什么名字**——纯函数，无 IO、无数据库、无提示词。
 *
 * 左栏列表、中栏标题、搜索框读的都是同一个字段，所以这一句决定整页叫它什么。
 *
 * **已记录的房号优先**：库里 `dwelling.unit` 是**唯一**记录房号的地方
 * （`lib/chat/coliving/repo.ts` 的「房号只从 `dwelling.unit` 读」）。住户说过、
 * 或者按房号并屋时写进去的那个房号，就是合作方认这套房时用的名字。
 *
 * **没记录过房号就原样回退 `household.label`**：导入名单给的可能是
 * 「Maple Court A 座 101」这种真名字，unit 留空时不能把它变成空字符串、
 * 也不能去正文里猜房号——label 是别人给这套房起的名字，丢了就找不回来。
 *
 * 三条容易做错的边界：
 *
 *   · **只用 trim，不做归一化。** `normalizeUnit` 那套（NFKC + 剥 `Unit` 前缀 +
 *     去空白 + 转小写）是**匹配键**，用来判断两个写法是不是同一间；拿它当显示值
 *     会把住户说的「A 208」显示成「a208」。这里显示的是**记录原样**。
 *   · **不拼前缀、不造名字。** 没有「Unit A208」这种补出来的抬头：库里记的是
 *     什么就显示什么，房号带不带楼栋由记录本身决定。
 *   · **这是一行的显示名，不是身份。** 两栋不同的房子完全可以是同一个房号
 *     （同一套房历史上的两段住户、或导入时的两种情况），所以**只按行算、
 *     绝不按房号合并或去重**——合并会让两组人的聊天记录在页面上塌成一条。
 */
export function unitDisplayName(
  unit: string | null | undefined,
  label: string
): string {
  const recorded = unit?.trim();
  return recorded ? recorded : label;
}
